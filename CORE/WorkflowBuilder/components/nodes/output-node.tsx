"use client";
import { apiUrl } from "@/lib/runtime-config";
import { getAccessToken } from "@/lib/api-client";

import { memo, useState, useCallback } from "react";
import { nodeStateBorderClass } from "@/lib/node-state-style";
import { nodeAriaLabel } from "@/lib/canvas-a11y";
import { Handle, Position, type NodeProps } from "reactflow";
// FX.72 p4b: React Flow's memoised graph hooks (zustand-backed, cheap) let an
// Output node ask which node feeds it, so the preview can carry the same
// "AI-generated" badge process-node.tsx puts on its own header.
import { useNodes, useEdges } from "reactflow";
import { upstreamIsAi } from "@/lib/ai-output-label";
import { FileOutput, Download, Loader2 } from "lucide-react";
import type { NodeData } from "@/lib/types";
import { getColorForType } from "@/lib/color-utils";
import { toast } from "@/components/ui/use-toast";
import { AssetPreview } from "./asset-preview";
import { NodeChips } from "../node-chips";
import { NodeStackOverlay } from "./node-stack-overlay";

const API_URL = apiUrl();

// Output nodes always have green border (their original color)
const getStatusColor = (): string => {
  return "border-green-500"; // Always green for output nodes
};

// Helper function to get background color for status indicator
const getStatusBgColor = (status?: string): string => {
  switch (status) {
    case "running":
      return "bg-green-400"; // Green pulse while running
    case "success":
      return "bg-green-500";
    case "failure":
      return "bg-red-500";
    case "queued":
      return "bg-purple-500";
    default:
      return "bg-gray-300"; // Default grey for no status
  }
};

const getSchemaEntries = (schema: { [key: string]: any } | undefined, legacyTypeKey: 'input_type' | 'output_type') => {
    if (!schema) return [];

    if (schema[legacyTypeKey]) {
        if (schema[legacyTypeKey] === 'NONE') return [];

        const types = schema[legacyTypeKey].split(',').map((t: string) => t.trim());
        const name = legacyTypeKey.replace('_type', '');

        return types.map((type: string, index: number) => ({
            name: types.length > 1 ? `${name}_${index}` : name,
            type,
        }));
    }

    return Object.entries(schema).map(([name, props]) => ({
        name,
        type: typeof props === 'object' && props !== null && props.type ? props.type : 'ANY',
    }));
};

export const OutputNode = memo(({ id, data, isConnectable }: NodeProps<NodeData>) => {
    const inputs = getSchemaEntries(data.input_schema, 'input_type');
    // FX.72 p4b: the graph hooks are memoised zustand reads — no per-frame walk.
    const graphNodes = useNodes();
    const graphEdges = useEdges();
    const aiGenerated = upstreamIsAi(id, graphNodes, graphEdges);
    const statusColor = nodeStateBorderClass(data, getStatusColor());
    const [isDownloading, setIsDownloading] = useState(false);

    const handleDownload = useCallback(async (e: React.MouseEvent) => {
        e.stopPropagation();

        // Get access token (sessionStorage since R-077)
        const accessToken = getAccessToken();
        if (!accessToken) {
            toast({
                title: "Authentication Error",
                description: "Please log in again to download files.",
                variant: "destructive"
            });
            return;
        }

        // Get workflow run ID from the node data or window event
        const workflowRunId = data.workflow_run_id || (window as any).__lastWorkflowRunId;

        if (!workflowRunId) {
            toast({
                title: "No Output Available",
                description: "Run the workflow first to generate output files.",
                variant: "destructive"
            });
            return;
        }

        setIsDownloading(true);

        try {
            // First, get the output folders for this workflow run
            const foldersResponse = await fetch(`${API_URL}/road/workflow-runs/${workflowRunId}/output-folders`, {
                headers: {
                    Authorization: `Bearer ${accessToken}`,
                    Accept: "application/json"
                },
            });

            if (!foldersResponse.ok) {
                throw new Error("Failed to fetch output folders");
            }

            const outputFolders = await foldersResponse.json();

            if (!outputFolders || outputFolders.length === 0) {
                toast({
                    title: "No Output Files",
                    description: "No output files were generated by this workflow.",
                    variant: "destructive"
                });
                setIsDownloading(false);
                return;
            }

            // If single folder, download it directly
            // If multiple folders, use download-multiple endpoint
            const cogIds = outputFolders.map((f: any) => f.id);

            toast({
                title: "Preparing Download",
                description: `Packaging ${outputFolders.length} output folder(s)...`
            });

            // Create download job
            const downloadResponse = await fetch(`${API_URL}/assets/download-jobs`, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    Authorization: `Bearer ${accessToken}`,
                },
                body: JSON.stringify({ cog_ids: cogIds }),
            });

            if (!downloadResponse.ok) {
                throw new Error("Failed to create download job");
            }

            const downloadJob = await downloadResponse.json();

            // Poll for completion
            const pollInterval = setInterval(async () => {
                try {
                    const statusResponse = await fetch(`${API_URL}/assets/download-jobs/${downloadJob.id}`, {
                        headers: { Authorization: `Bearer ${accessToken}` },
                    });

                    if (!statusResponse.ok) {
                        clearInterval(pollInterval);
                        setIsDownloading(false);
                        throw new Error("Failed to check download status");
                    }

                    const status = await statusResponse.json();

                    if (status.status === 'completed' && status.download_url) {
                        clearInterval(pollInterval);
                        setIsDownloading(false);

                        // Trigger download
                        const a = document.createElement('a');
                        a.style.display = 'none';
                        a.href = status.download_url;
                        a.download = status.filename || 'workflow_output.zip';
                        document.body.appendChild(a);
                        a.click();
                        document.body.removeChild(a);

                        toast({
                            title: "Download Started",
                            description: `Downloading ${status.filename || 'workflow_output.zip'}`
                        });
                    } else if (status.status === 'failed') {
                        clearInterval(pollInterval);
                        setIsDownloading(false);
                        toast({
                            title: "Download Failed",
                            description: status.error_message || "Failed to create download package.",
                            variant: "destructive"
                        });
                    }
                } catch (error) {
                    clearInterval(pollInterval);
                    setIsDownloading(false);
                    console.error("Download poll error:", error);
                }
            }, 1500);

            // Timeout after 5 minutes
            setTimeout(() => {
                clearInterval(pollInterval);
                if (isDownloading) {
                    setIsDownloading(false);
                    toast({
                        title: "Download Timeout",
                        description: "Download is taking too long. Please try again.",
                        variant: "destructive"
                    });
                }
            }, 300000);

        } catch (error) {
            console.error("Download error:", error);
            toast({
                title: "Download Error",
                description: (error as Error).message || "Failed to download output files.",
                variant: "destructive"
            });
            setIsDownloading(false);
        }
    }, [data.workflow_run_id, isDownloading]);

  // text-foreground — ReactFlow's stylesheet paints `.react-flow__node-output`
  // (this node's type is "output") with color:#222, which every uncoloured
  // label inherits; in dark mode the card turns dark and that #222 text goes
  // black-on-black. Setting an explicit theme-aware foreground colour on the
  // root neutralises the inherited #222 so text stays readable in both themes —
  // the same effective colour the process node already gets for free.
  const nodeAriaLabelValue = nodeAriaLabel("output", data.label);

  return (
    <div role="group" aria-label={nodeAriaLabelValue} className={`px-4 pt-6 pb-2 shadow-md rounded-md bg-white text-foreground border-2 ${statusColor} w-max transition-colors duration-300 relative`}>
      <NodeStackOverlay nodeKind={(data as any)?.node_kind} requiresStack={(data as any)?.requires_stack} />
      {/* Status indicator box in top-right corner */}
      <div className={`absolute -top-2 -right-2 w-5 h-5 rounded ${getStatusBgColor(data.status)} border-2 border-white shadow-sm transition-colors duration-300 ${data.status === 'running' ? 'animate-pulse' : ''}`}></div>

        <div>
          <div className="flex items-center gap-2">
            <div className="rounded-full w-8 h-8 flex-shrink-0 flex items-center justify-center bg-green-100 text-green-500">
            <FileOutput className="h-4 w-4" />
            </div>
            <div className="text-sm font-bold whitespace-nowrap">{data.label || "Output"}</div>

            {/* Download button - show after workflow success */}
            {data.status === 'success' && (
                <button
                    onClick={handleDownload}
                    disabled={isDownloading}
                    className="ml-2 p-1.5 rounded-md bg-green-500 hover:bg-green-600 text-white transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
                    title="Download output files"
                >
                    {isDownloading ? (
                        <Loader2 className="h-3.5 w-3.5 animate-spin" />
                    ) : (
                        <Download className="h-3.5 w-3.5" />
                    )}
                </button>
            )}
          </div>
          {data.nickname && <div className="text-[11px] text-gray-500 truncate mt-0.5 pl-10">{data.nickname}</div>}
        </div>
        {data.description && (
            <div className="text-xs text-gray-500 mt-1 max-w-xs">
            {data.description}
            </div>
        )}

        {/* Preview area */}
        {data.status === 'success' && data.previewAssets && data.previewAssets.length > 0 && (
            <div className="w-56 mt-2 border-t border-gray-100 pt-2">
                <AssetPreview assets={data.previewAssets} aiGenerated={aiGenerated} />
            </div>
        )}
        {data.status === 'running' && (
            <div className="w-56 mt-2 flex items-center justify-center py-3">
                <Loader2 className="h-4 w-4 animate-spin text-green-400 mr-2" />
                <span className="text-[10px] text-gray-400">Packaging...</span>
            </div>
        )}
        {data.status === 'failure' && (
            <div className="w-56 mt-2 flex flex-col items-center py-2">
                <span className="text-red-400 text-sm font-bold">!</span>
                <span className="text-[10px] text-red-400">Failed</span>
                {data.error_message && (
                    <span className="text-[9px] text-red-300 text-center line-clamp-2 max-w-full mt-0.5">
                        {data.error_message}
                    </span>
                )}
            </div>
        )}

        {/* LDF-3 §3 — credit + processing chips, bottom-right corner */}
        <div className="absolute bottom-1 right-1 z-10 pointer-events-none">
            <NodeChips
                cost={data.cost_in_credits}
                gpuVariants={data.gpu_variants}
            />
        </div>

        {inputs.map((input: { name: string; type: string }, index: number) => (
          <Handle
            key={input.name}
            type="target"
            position={Position.Top}
            id={input.name}
            title={`Input: ${input.name} (${input.type})`}
            style={{
              left: `${(100 / (inputs.length + 1)) * (index + 1)}%`,
              backgroundColor: getColorForType(input.type),
            }}
            isConnectable={isConnectable}
            className="w-25 h-25"
          />
        ))}
    </div>
  );
});

OutputNode.displayName = "OutputNode";
