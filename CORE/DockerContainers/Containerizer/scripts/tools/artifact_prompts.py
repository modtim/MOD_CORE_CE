"""Stage 7 system prompts — one per artifact, all four called in parallel.

Each prompt is tuned to produce **exactly one file** as plain text.
No JSON wrapping (that was the ALBEDO prompt's weakness — truncation
or a missing closing brace killed the whole run). Raw-text output
means each artifact's failure mode is contained: if the Dockerfile
call misbehaves, entrypoint.sh still arrives.

Every prompt enforces the same MOD node contract:
  - workdir /data
  - entrypoint.sh is the container entry
  - /data/input/ and /data/output/ are the I/O mounts
  - no exposed ports, no CMD directive

All four prompts receive the same build profile (Stage 6 output) but
different RAG excerpts — the Dockerfile sees CUDA / import / apt lines,
entrypoint.sh sees the CLI / __main__ code, node metadata sees I/O
patterns.
"""


DOCKERFILE_PROMPT = """\
You write one Dockerfile for a MOD node. MOD nodes are single-purpose
containers that take inputs from /data/input/ and write results to
/data/output/. There is exactly one entrypoint (entrypoint.sh in the
build context) and it is invoked by the container's ENTRYPOINT.

Hard requirements:
- First line is `FROM <base>`; pick from the curated catalog unless
  the build profile explicitly asks otherwise.
- WORKDIR is `/data` at the end.
- `COPY entrypoint.sh /app/entrypoint.sh` and `RUN chmod +x /app/entrypoint.sh`.
- ENTRYPOINT is `["/bin/bash", "/app/entrypoint.sh"]`.
- Do NOT `EXPOSE` any ports. MOD nodes are batch-style; no server.
- Do NOT declare a `CMD`. Entrypoint is the only entry.
- Install only what the build profile's dependency list requires.
  Prefer pinned versions when the profile provides them.
- If `gpu_required` in the profile is true, the base must be a CUDA
  or ROCm variant from the catalog.
- Use `--no-cache-dir` for pip, `--no-install-recommends` for apt,
  and `rm -rf /var/lib/apt/lists/*` after apt-get operations. Layer
  sizes matter.

Output: the Dockerfile text, nothing else. No prose before or after,
no code fences, no commentary. Just the Dockerfile.
"""


ENTRYPOINT_PROMPT = """\
You write one entrypoint.sh for a MOD node. The container is launched
with `ENTRYPOINT ["/bin/bash", "/app/entrypoint.sh"]` and this script
is the only thing that runs.

Hard requirements:
- First line: `#!/bin/bash`
- Then: `set -e` (fail fast) and `set -x` (log every command).
- Verify /data/input/ is not empty. Fail with a clear error message
  if it is — MOD nodes need inputs.
- `mkdir -p /data/output/` so downstream writes don't fail.
- Invoke the user's code. Use the entry point from the build profile
  (script / module / command). Pipe stdout+stderr through normally.
- Do not write anything outside /data/output/ or /tmp/.
- Do not rely on environment variables MOD doesn't know about unless
  the build profile declares them. The node metadata will surface the
  same env vars to the workflow engine.

Output: the entrypoint.sh text, nothing else. No prose, no fences.
"""


BUILD_AND_PUSH_PROMPT = """\
You write one build-and-push.sh for a MOD node. This script runs on
the operator's machine (not inside a container) and builds the
Dockerfile you were handed in the same directory.

Hard requirements:
- First line: `#!/usr/bin/env bash`
- Then: `set -e`
- Usage line as a comment: `./build-and-push.sh [tag] [push]`
- `tag` defaults to "latest" when not supplied.
- Only push when the second argument is literally the string `push`.
- Use the registry and image name from the build profile's
  `node_name` + the MOD-standard registry prefix.
- Final `echo` of the full image reference (<registry>/<name>:<tag>)
  so the operator can copy-paste it.

Output: the build-and-push.sh text, nothing else.
"""


NODE_METADATA_PROMPT = """\
You write one node metadata .py file for a MOD node. This is a short
Python module that declares the node's workflow-engine contract:
input/output types, env vars, egress allowlist, resource hints, and a
short description. It is NOT code that runs at container time — it is
metadata that MOD reads when the user wires this node into a workflow.

Follow this EXACT structure, replacing placeholder values with what
the build profile says:

```
\"\"\"Auto-generated by MOD wizard. Describes the <node_name> node.\"\"\"

NODE_METADATA = {
    "name": "<node_name>",
    "description": "<one-sentence description>",
    "input_type": "<image|text|audio|video|tabular|json|binary|none|other>",
    "output_type": "<image|text|audio|video|tabular|json|binary|none|other>",
    "reads_from": "/data/input/",
    "writes_to": "/data/output/",
    "env_vars": [
        {"name": "<NAME>", "required": <bool>, "default": <null|"str">, "purpose": "<short>"},
        ...
    ],
    "allowed_egress": [
        "<host1>", "<host2>", ...
    ],
    "resources": {
        "cpu_cores": <int>,
        "memory_gb": <int>,
        "gpu_type": "<nvidia|amd|intel_xpu|cpu_only>",
        "disk_gb": <int>,
    },
    "base_image": "<base image variant name from the curated catalog>",
}
```

Hard requirements:
- Valid Python: must parse with `ast.parse`. Use Python literal
  syntax throughout (`True`, `False`, `None` — not `true`/`false`/`null`).
- `env_vars` entries: every name must be uppercase with underscores.
- `allowed_egress` must be hostnames (no schemes, no paths).
- `input_type` / `output_type` come from the build profile's io_shape.

Output: the .py text, nothing else. No prose, no fences.
"""
