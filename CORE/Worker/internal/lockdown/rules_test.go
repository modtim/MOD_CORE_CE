// decodeNftQuoted reads one nft double-quoted literal that must span the whole
// of s. It accepts only \\ and \" escapes and fails on any unescaped quote
// before the end, so a broken closing quote is detected.
func decodeNftQuoted(s string) (string, bool) {
	if len(s) < 2 || s[0] != '"' || s[len(s)-1] != '"' {
		return "", false
	}
	inner := s[1 : len(s)-1]
	var b strings.Builder
	for i := 0; i < len(inner); i++ {
		switch c := inner[i]; c {
		case '\\':
			if i+1 >= len(inner) || (inner[i+1] != '\\' && inner[i+1] != '"') {
				return "", false
			}
			b.WriteByte(inner[i+1])
			i++
		case '"':
			return "", false
		default:
			b.WriteByte(c)
		}
	}
	return b.String(), true
}

func TestQuoteTable(t *testing.T) {
	cases := []struct {
		in, want string
	}{
		{"a", `"a"`},
		{`a"b`, `"a\"b"`},
		{`a\`, `"a\\"`},
		{`a\"b`, `"a\\\"b"`},
		{`\\`, `"\\\\"`},
		{"system.slice/mod-tailscaled-site.service", `"system.slice/mod-tailscaled-site.service"`},
	}
	for _, c := range cases {
		if got := quote(c.in); got != c.want {
			t.Errorf("quote(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

func TestQuoteRoundTrip(t *testing.T) {
	inputs := []string{`a`, `a"b`, `a\`, `a\"b`, `\`, `"`, `\\"\`, "unicode-é"}
	for _, in := range inputs {
		got, ok := decodeNftQuoted(quote(in))
		if !ok {
			t.Errorf("quote(%q) = %q: closing quote is not a clean terminator", in, quote(in))
			continue
		}
		if got != in {
			t.Errorf("round trip of %q gave %q", in, got)
		}
	}
}

func TestRenderTrailingBackslashCgroup(t *testing.T) {
	p := EmptyPolicy()
	p.TailscaledCgroups = []string{`system.slice/x\`}
	out := Render(p)
	want := "\t\tsocket cgroupv2 level 2 \"system.slice/x\\\\\" accept\n"
	if !strings.Contains(out, want) {
		t.Fatalf("trailing-backslash cgroup not rendered as %q in:\n%s", want, out)
	}
}

func TestRenderDropsControlCharCgroup(t *testing.T) {
	p := EmptyPolicy()
	p.TailscaledCgroups = []string{"bad\nname", "bad\x00nul", "ok.slice/svc"}
	out := Render(p)
	if strings.Contains(out, "bad") {
		t.Fatalf("control-character cgroup was emitted:\n%s", out)
	}
	if !strings.Contains(out, "\"ok.slice/svc\" accept\n") {
		t.Fatalf("valid cgroup missing after dropping invalid ones:\n%s", out)
	}
}

func TestHasControl(t *testing.T) {
	if hasControl("plain/path-ok_1.service") || hasControl("unicode-é") {
		t.Error("hasControl flagged a printable string")
	}
	for _, s := range []string{"a\nb", "a\x00", "a\x7f", "a\u0085"} {
		if !hasControl(s) {
			t.Errorf("hasControl(%q) = false, want true", s)
		}
	}
}

// FIX-GO-LOCKDOWN-HASCONTROL-INVALID-UTF8: ranging over a string yields U+FFFD
// for each invalid UTF-8 byte, so raw invalid bytes used to slip through the
// control check and reach the nft text. They must be rejected like control
// characters; valid non-ASCII UTF-8 must still be accepted.
func TestHasControlInvalidUTF8(t *testing.T) {
	// ACCEPTED: printable ASCII and valid non-ASCII UTF-8 (not ASCII-only).
	for _, s := range []string{"ok", "é", "日本", "a b"} {
		if hasControl(s) {
			t.Errorf("hasControl(%q) = true, want false", s)
		}
	}
	// REJECTED: invalid UTF-8 (raw byte, embedded raw byte, truncated
	// multibyte, lone continuation byte, truncated 3-byte sequence) plus the
	// existing control characters (newline, NUL, ESC, DEL, C1).
	for _, s := range []string{"\xff", "a\xffb", "\xc3\x28", "\x80", "\xe2\x82",
		"a\nb", "a\x00", "a\x1b", "a\x7f", "a\u0085"} {
		if !hasControl(s) {
			t.Errorf("hasControl(%q) = false, want true", s)
		}
	}
}

// The real caller path: Render must drop invalid-UTF-8 cgroups (fail closed),
// same style as the control-character drop, and keep the valid ones.
func TestRenderDropsInvalidUTF8Cgroup(t *testing.T) {
	p := EmptyPolicy()
	p.TailscaledCgroups = []string{"\xff", "a\xffb", "\xc3\x28", "\x80", "\xe2\x82",
		"ok.slice/svc", "unicode-é.slice/svc"}
	out := Render(p)
	for _, bad := range []string{"\xff", "a\xffb", "\xc3\x28", "\x80", "\xe2\x82"} {
		if strings.Contains(out, bad) {
			t.Fatalf("invalid-UTF-8 cgroup %q was emitted:\n%s", bad, out)
		}
	}
	if !strings.Contains(out, "\"ok.slice/svc\" accept\n") {
		t.Fatalf("valid cgroup missing after dropping invalid ones:\n%s", out)
	}
	if !strings.Contains(out, "\"unicode-é.slice/svc\" accept\n") {
		t.Fatalf("valid non-ASCII cgroup dropped:\n%s", out)
	}
}

func reverseAP(v []netip.AddrPort) []netip.AddrPort {
	rev := append([]netip.AddrPort(nil), v...)
	for i, j := 0, len(rev)-1; i < j; i, j = i+1, j-1 {
		rev[i], rev[j] = rev[j], rev[i]
	}
	return rev
}

