// TestRenderForwardIPv6Bridge covers the per-family split in forwardRules: a
// v6-only bridge must never pair with the v4 allow-set (nft rejects a rule
// mixing `ip saddr` with `ip6 daddr` as "conflicting protocols").
func TestRenderForwardIPv6Bridge(t *testing.T) {
	p := FullPolicy()
	p.DockerBridgeRanges = []netip.Prefix{mustPrefix("fd00:d0c:e5::/48")}
	got := Render(p)
	if strings.Contains(got, "ip saddr") {
		t.Errorf("a v6-only bridge must not emit an `ip saddr` (v4) forward rule:\n%s", got)
	}
	if !strings.Contains(got, "ct state new ip6 saddr { fd00:d0c:e5::/48 }") {
		t.Errorf("expected a v6 saddr forward rule for the v6 bridge:\n%s", got)
	}
}

func TestRenderInputOrder(t *testing.T) {
	reversed := FullPolicy()
	reversed.AllowIPs = reverseAP(reversed.AllowIPs)
	reversed.DNS = reverseAddr(reversed.DNS)
	reversed.DockerBridgeRanges = reversePrefix(reversed.DockerBridgeRanges)
	if Render(reversed) != Render(FullPolicy()) {
		t.Errorf("input order changed output")
	}
}

