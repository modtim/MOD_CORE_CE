// Package lockdown renders the worker-managed host firewall for declared egress
// (design.md H2): one nftables table, `inet mod_lockdown`, applied atomically by
// the reconciler via `nft -f -` (delete + create in one transaction).
//
// Pure: no exec, no file I/O, no clock. Output is deterministic - every input
// list is deduped and sorted - so the golden tests in rules_test.go are stable.
package lockdown

import (
	"net/netip"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

const (
	TableFamily = "inet"
	TableName   = "mod_lockdown"
	// OutputChain must not be "policy" - that is an nft grammar keyword
	// (the `policy drop;` chain-type statement) and "chain policy { ... }"
	// fails to parse.
	OutputChain  = "output"
	ForwardChain = "forward"
	TailnetOIF   = "tailscale*"
	CgroupLevel  = 2
	Reason       = "mod declared-egress lockdown"
)

// PrivateRanges are the RFC1918 ranges: never a route to the internet.
var PrivateRanges = []netip.Prefix{
	netip.MustParsePrefix("10.0.0.0/8"),
	netip.MustParsePrefix("172.16.0.0/12"),
	netip.MustParsePrefix("192.168.0.0/16"),
}

// Policy is the resolved host-lockdown policy for one worker.
type Policy struct {
	AllowIPs           []netip.AddrPort
	DNS                []netip.Addr
	TailnetV4          netip.Prefix
	TailnetV6          netip.Prefix
	TailscaledCgroups  []string
	DockerBridgeRanges []netip.Prefix
	ForwardDrop        bool
}

// Render returns ONE atomic nft script: the delete+add preamble makes
// re-application idempotent, and the whole file is one transaction, so a crash
// leaves either the old table or the new one (fail closed).
func Render(p Policy) string {
	allow := sortedBy(p.AllowIPs, addrPortKey)
	dns := sortedBy(p.DNS, addrKey)
	cgroups := sortedBy(p.TailscaledCgroups, identityKey)
	bridges := sortedBy(p.DockerBridgeRanges, prefixKey)
	tailnets := sortedBy(tailnetPrefixes(p), prefixKey)

	var b strings.Builder
	b.WriteString("# mod_lockdown - generated by Worker/internal/lockdown; do not edit.\n")
	b.WriteString("# add + delete + table are one transaction: re-apply is idempotent.\n")
	b.WriteString("add table " + TableFamily + " " + TableName + "\n")
	b.WriteString("delete table " + TableFamily + " " + TableName + "\n")
	b.WriteString("table " + TableFamily + " " + TableName + " {\n")
	b.WriteString("\tchain " + OutputChain + " {\n")
	b.WriteString("\t\ttype filter hook output priority 0; policy drop;\n")
	for _, line := range outputRules(allow, dns, tailnets, cgroups) {
		b.WriteString("\t\t" + line + "\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("\tchain " + ForwardChain + " {\n")
	b.WriteString("\t\ttype filter hook forward priority -1; policy accept;\n")
	allowSet := sortedBy(forwardAllowSet(allow, dns, tailnets), prefixKey)
	for _, line := range forwardRules(bridges, allowSet, p.ForwardDrop) {
		b.WriteString("\t\t" + line + "\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("}\n")
	return b.String()
}

// tailnetPrefixes drops unset prefixes (an invalid/zero-length netip.Prefix),
// so an empty tailnet contributes no accept rules.
func tailnetPrefixes(p Policy) []netip.Prefix {
	var out []netip.Prefix
	for _, pfx := range []netip.Prefix{p.TailnetV4, p.TailnetV6} {
		if pfx.IsValid() {
			// A /0 prefix would accept everything: treat it as unset.
			if pfx.Bits() > 0 {
				out = append(out, pfx)
			}
		}
	}
	return out
}

// sortedBy returns a deduped ascending copy of items ordered by key string.
func sortedBy[T any](items []T, key func(T) string) []T {
	out := append([]T(nil), items...)
	sort.SliceStable(out, func(i, j int) bool { return key(out[i]) < key(out[j]) })
	var uniq []T
	for i := range out {
		if i > 0 && key(out[i]) == key(out[i-1]) {
			continue
		}
		uniq = append(uniq, out[i])
	}
	return uniq
}

func identityKey(s string) string { return s }

func addrPortKey(ap netip.AddrPort) string { return ap.String() }
func addrKey(a netip.Addr) string          { return a.String() }
func prefixKey(pfx netip.Prefix) string    { return pfx.String() }

// ipProto returns the nft payload keyword ("ip" or "ip6") that matches a's
// family: an inet-family table needs the explicit keyword on every address
// match (a bare `daddr` is ambiguous without one).
func ipProto(a netip.Addr) string { return ipProtoV(a.BitLen() == 32) }

// ipProtoV is ipProto keyed on an already-known v4/v6 flag.
func ipProtoV(ipv4 bool) string {
	if ipv4 {
		return "ip"
	}
	return "ip6"
}

// outputRules builds the `output` hook accepts (design H2, bullet 1).
func outputRules(allow []netip.AddrPort, dns []netip.Addr, tailnets []netip.Prefix, cgroups []string) []string {
	var r []string
	r = append(r, "# reason: "+Reason)
	// oifname "lo" covers all loopback traffic (both families); matching on
	// `saddr 127.0.0.1`/`::1` instead would miss traffic that merely routes
	// via lo without that exact source (and is not valid nft grammar for
	// "any loopback" the way a source-address match is).
	r = append(r, "oifname \"lo\" accept")
	r = append(r, "ct state { established, related } accept")
	r = append(r, "udp sport { 67, 68 } accept")
	r = append(r, "icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert, nd-router-solicit, nd-router-advert } accept")
	for _, a := range dns {
		proto := ipProto(a)
		r = append(r, proto+" daddr "+a.String()+" udp dport 53 accept")
		r = append(r, proto+" daddr "+a.String()+" tcp dport 53 accept")
	}
	for _, ap := range allow {
		proto := ipProto(ap.Addr())
		r = append(r, proto+" daddr "+ap.Addr().String()+" tcp dport "+strconv.Itoa(int(ap.Port()))+" accept")
		r = append(r, proto+" daddr "+ap.Addr().String()+" udp dport "+strconv.Itoa(int(ap.Port()))+" accept")
	}
	for _, pfx := range tailnets {
		proto := ipProto(pfx.Addr())
		r = append(r, "oifname \""+TailnetOIF+"\" "+proto+" daddr "+pfx.String()+" accept")
	}
	for _, cg := range cgroups {
		if hasControl(cg) {
			continue // not renderable as an nft literal: drop (fail closed)
		}
		r = append(r, "socket cgroupv2 level "+strconv.Itoa(CgroupLevel)+" "+quote(cg)+" accept")
	}
	return r
}

// forwardRules builds the `forward` hook (design H2, bullet 2): prio -1 runs
// before Docker's chains, so a NEW flow that starts on a docker bridge and aims
// outside the allow set is dropped (OD-H4: stacks lose internet egress too).
func forwardRules(bridges []netip.Prefix, allowSet []netip.Prefix, forwardDrop bool) []string {
	// Return traffic for already-accepted flows needs no explicit rule here:
	// the chain's own `policy accept` (set in Render) passes it, same as any
	// non-NEW packet that never matches one of the NEW-only rules below.
	var r []string
	if !forwardDrop || len(bridges) == 0 {
		return r
	}
	// Bridges and the allow-set must be split per IP family: nft rejects a
	// rule mixing an `ip saddr` set with an `ip6 daddr` set ("conflicting
	// protocols"), so a v4-only bridge list must never gain a v6 daddr
	// clause (and vice versa).
	for _, ipv4 := range []bool{true, false} {
		proto := ipProtoV(ipv4)
		famBridges := prefixesFor(bridges, ipv4)
		if len(famBridges) == 0 {
			continue
		}
		bridgeSet := brace(famBridges)
		allow := brace(prefixesFor(allowSet, ipv4))
		if allow != "{}" {
			r = append(r, "ct state new "+proto+" saddr "+bridgeSet+" "+proto+" daddr "+allow+" accept")
		}
		r = append(r, "ct state new "+proto+" saddr "+bridgeSet+" drop")
	}
	return r
}

// forwardAllowSet is every destination the forward chain must NOT drop: the
// allow IPs, the DNS servers, the tailnet prefixes and the private ranges.
func forwardAllowSet(allow []netip.AddrPort, dns []netip.Addr, tailnets []netip.Prefix) []netip.Prefix {
	var out []netip.Prefix
	for _, ap := range allow {
		out = append(out, netip.PrefixFrom(ap.Addr(), addrBits(ap.Addr())))
	}
	for _, a := range dns {
		out = append(out, netip.PrefixFrom(a, addrBits(a)))
	}
	out = append(out, tailnets...)
	out = append(out, PrivateRanges...)
	return out
}

// prefixesFor keeps the prefixes nft can match on one IP protocol.
func prefixesFor(prefixes []netip.Prefix, ipv4 bool) []netip.Prefix {
	var out []netip.Prefix
	for _, pfx := range prefixes {
		if (pfx.Addr().BitLen() == 32) == ipv4 {
			out = append(out, pfx)
		}
	}
	return out
}

// brace renders prefixes as an nft set literal; empty sets become /0-free {}.
func brace(prefixes []netip.Prefix) string {
	var parts []string
	for _, pfx := range prefixes {
		// nft rejects a /0 range in a set alongside concrete ones; keep it out.
		if pfx.Bits() > 0 {
			parts = append(parts, pfx.String())
		}
	}
	if len(parts) == 0 {
		return "{}"
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// quote renders a cgroup path as an nft string literal. The backslash is
// escaped FIRST and the double quote second, so a value ending in a backslash
// cannot escape the closing quote and a value containing \" round-trips.
// Control characters are rejected earlier (see hasControl in Render).
func quote(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "\"", "\\\"")
	return "\"" + s + "\""
}

// hasControl reports whether s contains a control character (C0, DEL, C1),
// or is not valid UTF-8 at all. An nft string literal cannot carry a raw
// newline or NUL, so Render drops such entries instead of emitting a broken
// transaction. Invalid UTF-8 is rejected the same way: ranging over a string
// yields U+FFFD for each invalid byte, which would slip through the control
// check and be emitted raw into the nft literal. Valid non-ASCII UTF-8
// (letters like 'é', CJK) is still accepted - this is not an ASCII-only rule.
func hasControl(s string) bool {
	if !utf8.ValidString(s) {
		return true
	}
	for _, r := range s {
		if r < 0x20 || (r >= 0x7f && r <= 0x9f) {
			return true
		}
	}
	return false
}

// addrBits is 32 for IPv4, 128 for IPv6.
func addrBits(a netip.Addr) int {
	if a.BitLen() == 32 {
		return 32
	}
	return 128
}
