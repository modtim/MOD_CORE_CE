"""managed-ai-surfaces-and-stack-ops §4 — tenant-attributed LLM token metering.

No LLM call records who made it or what it cost. `llm_usage` is keyed
(tool, base_url, model) GLOBALLY with a call counter — it exists to drive idle
reclaim, not billing, and has no tenant. `AssistantMessage` records tokens and a
tenant but only for the assistant, and only because chat history needed rows
anyway.

So the platform cannot answer "what did this tenant's AI usage cost us", which
blocks both pricing and the rate-limit defaults, since those should come from
observed p95 rather than a guess.

WHY PER-CALL AND NOT A COUNTER. A short chat turn and a large-prompt wizard call
differ by more than an order of magnitude — measured: 3.9s versus 20s on GPU,
and 15k input tokens versus 50. A per-call counter cannot tell them apart, so
per-call rows are the only shape that supports pricing later.

WHY CHANNEL. require_bearer_or_api_key already distinguishes API key, API key
carried as a bearer token, and a browser session — then discards it. Programmatic
and interactive load have different cost and different growth, and neither can be
priced or capacity-planned before the split has been measured.

Adds:
  - llm_call_usage        — one row per call
  - tenant_llm_usage_daily — rollup, mirroring tenant_egress_usage_daily

Additive + idempotent. Run inside the API container:
    docker exec my_fastapi_app python3 \\
        migrations/20260803_add_llm_call_metering.py --commit
"""
from __future__ import annotations

import argparse
import os
import sys


# `succeeded` is deliberately present: input tokens are consumed whether or not
# generation completed, so a failed call still cost real GPU time and must be
# visible. Recording only successes would understate load exactly when the
# platform is struggling.
CALL_SQL = """
CREATE TABLE IF NOT EXISTS llm_call_usage (
    id                BIGSERIAL PRIMARY KEY,
    tenant_id         INTEGER NOT NULL,
    user_id           INTEGER,
    tool              VARCHAR(64) NOT NULL,
    model             VARCHAR(255),
    base_url          VARCHAR(512),
    -- 'programmatic' (API key, however carried) or 'interactive' (browser).
    channel           VARCHAR(16) NOT NULL DEFAULT 'unknown',
    prompt_tokens     INTEGER NOT NULL DEFAULT 0,
    completion_tokens INTEGER NOT NULL DEFAULT 0,
    succeeded         BOOLEAN NOT NULL DEFAULT TRUE,
    duration_ms       INTEGER,
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_llm_call_usage_tenant_time
    ON llm_call_usage(tenant_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_llm_call_usage_time
    ON llm_call_usage(occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_llm_call_usage_tool
    ON llm_call_usage(tool);
"""

# One row per (tenant, day, tool, model, channel), mirroring
# tenant_egress_usage_daily. The per-call table answers "what happened"; this
# answers "what did the month look like" without scanning every call.
DAILY_SQL = """
CREATE TABLE IF NOT EXISTS tenant_llm_usage_daily (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         INTEGER NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    day               DATE NOT NULL,
    tool              VARCHAR(64) NOT NULL,
    model             VARCHAR(255) NOT NULL DEFAULT '',
    channel           VARCHAR(16) NOT NULL DEFAULT 'unknown',
    calls             BIGINT NOT NULL DEFAULT 0,
    failed_calls      BIGINT NOT NULL DEFAULT 0,
    prompt_tokens     BIGINT NOT NULL DEFAULT 0,
    completion_tokens BIGINT NOT NULL DEFAULT 0,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_tenant_llm_usage_daily
        UNIQUE (tenant_id, day, tool, model, channel)
);
CREATE INDEX IF NOT EXISTS ix_tenant_llm_usage_daily_tenant_day
    ON tenant_llm_usage_daily(tenant_id, day DESC);
"""

STATEMENTS = [CALL_SQL, DAILY_SQL]


def _get_conn():
    sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))
    import database as _db  # type: ignore
    _db.initialize()
    eng = _db.get_engine()
    if eng is None:
        raise RuntimeError("Database engine is None; check Vault creds.")
    raw = eng.raw_connection()
    dbapi = (getattr(raw, "driver_connection", None)
             or getattr(raw, "connection", None) or raw)
    dbapi.autocommit = True
    return dbapi


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--commit", action="store_true")
    args = p.parse_args()
    if not args.commit:
        for s in STATEMENTS:
            print(s)
        print("(dry-run; pass --commit to apply)")
        return 0
    conn = _get_conn()
    cur = conn.cursor()
    for s in STATEMENTS:
        cur.execute(s)
    cur.close()
    print("llm metering ready: llm_call_usage (per call), "
          "tenant_llm_usage_daily (rollup).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
