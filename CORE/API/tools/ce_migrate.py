#!/usr/bin/env python3
"""ce-migrate — the ONE-SHOT CE DB-migration step.

A CE in-place update (README "Choosing images": new CE_IMAGE_TAG, `compose
pull`, `up -d`) never applied CORE/API/migrations/*.py, so an rc17 image on an
rc16 DB 500s on POST /v1/road/ (`UndefinedColumn: column "slug" of
relation "workflows"`, added by migrations/20261027d_workflow_slug_graph_hash.py)
— CE boot never runs migrations (CORE/API/main.py:522 comment). The internal product proves the
pattern: CORE/startup/install.sh:581-585 runs
`docker compose --profile migrate run --rm mod-migrate || die "…the platform was
NOT started…"` BEFORE `up -d`, and update.sh:935 runs it on every update. CE
ships no install.sh, so the one-shot lives in open-core/overlay/docker-compose.yml
as the `mod-migrate` service, whose entrypoint is this file.

ONE path for fresh AND in-place: create_tables() first (idempotent — version gate
database.py:853, and api's own boot call at main.py:236 stays), then every
migrations/*.py through tools/mod_migrate.py, each recorded in the append-only
`release_steps` ledger. A pre-ledger DB (cr12 / Tim's box: schema built, ledger
empty) therefore baselines by re-applying every migration, which is safe because
every step is IF NOT EXISTS / inspector-guarded.

CE skip list: a handful of internal migrations are pure internal-
HISTORY data — they insert/backfill rows under named tenant/user ids (QA tenants
28/29, the tenant-1 audit backfill) that do not exist on a CE DB, so they fail
ForeignKeyViolation there (observed: clone died at
20260907_repair_node_config_schema_and_seed_qa_tenants after ~345 s; empty DB
died at 20260513_tiered_credit_pricing after ~8 s, which would have blocked api
start on EVERY CE install). ce_migrate therefore passes
`--skip-file tools/ce_migrate_skip.txt` to mod_migrate (rule:
a step may be listed ONLY if ALL its effects are internal-history data — any DDL or
row CE needs must NOT be listed). The steps are neither run nor recorded, so
they stay pending for internal use if the file is ever used there.

Failure is fatal by design: a non-zero exit here blocks `api`
(depends_on: mod-migrate: service_completed_successfully), so the install never
serves a half-migrated schema — `docker compose logs mod-migrate` names the step.
"""
from __future__ import annotations

import os
import sys

# Same sys.path shape as tools/mod_migrate.py:95 (API_DIR) + :230-231
# (sys.path.insert(API_DIR) then `import database`), so this file works both as
# `python3 tools/ce_migrate.py` inside the api image (WORKDIR /app) and as a
# file-loaded module in the API test suite.
API_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# BUG-1027w-b: the CE skip list, absolute so it resolves the same from any cwd
# (compose WORKDIR /app, the test suite's cwd, an installer shell).
SKIP_FILE = os.path.join(API_DIR, "tools", "ce_migrate_skip.txt")

# P18-F1b: the fresh-install baseline manifest (GENERATED by tools/gen_fresh_baseline.py —
# consumed here only, never edited). Absolute so it resolves the same from any cwd,
# same shape as SKIP_FILE.
FRESH_BASELINE = os.path.join(API_DIR, "tools", "fresh_install_baseline.txt")

# CE-NOPAID-4.13d: the paid add-on migrations dir (the CE-NOPAID-4.15 layout; the
# 4.9c compliance-class moves land there). Absolute like SKIP_FILE. Forwarded to
# mod_migrate ONLY on a paid tree — the CE carve has no such dir, and a missing
# dir is a no-op there (CE-NOPAID-4.13c: mod_migrate logs one line, zero steps,
# exit 0). Nothing here creates the dir.
PAID_MIGRATIONS_DIR = os.path.join(API_DIR, "paid_addon", "migrations")


def _fresh_db_gate(db) -> bool:
    """P18-F1b: True ONLY when the DB is from-scratch: (a) the release_steps ledger
    is empty/absent AND (b) no mod_schema_version marker for the current schema
    version. Call BETWEEN initialize() and create_tables() — create_tables'
    _bootstrap_ddl_single_flight -> _migrate_schema (database.py:832) writes that
    marker, so reading it AFTER create_tables would lie. A migrated DB is NEVER
    baselined. Exceptions (absent tables) count as empty; the exception message is
    never printed (it may carry a DSN)."""
    from sqlalchemy import text as sa_text
    try:
        engine = db.get_engine()
    except Exception:
        return False
    try:
        with engine.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
            try:
                if conn.execute(sa_text("SELECT 1 FROM release_steps LIMIT 1")).first():
                    return False  # (a) ledger has entries -> migrated DB
            except Exception:
                pass  # ledger table absent -> empty
            try:
                if conn.execute(sa_text(
                        "SELECT 1 FROM mod_schema_version WHERE version=:v"),
                        {"v": db._SCHEMA_MIGRATION_VERSION}).first():
                    return False  # (b) marker present -> schema built before this run
            except Exception:
                pass  # marker table absent -> DB empty before create_tables
        return True
    except Exception:
        return False


def main(argv=None) -> int:
    """initialize() -> create_tables() -> mod_migrate.main(argv). 0 = schema current.

    `argv` is forwarded verbatim to tools/mod_migrate.py:431
    (`main(argv: Optional[list[str]] = None) -> int`), so the compose service's
    `command: [--no-seeds]` reaches it (CE seeds run in-process at api boot —
    main.py:398 seed_ce_admin_user, main.py:3701 seed_platform_settings).

    BUG-1027w-b: unless the caller already passed `--skip-file`, this appends
    `--skip-file <abs tools/ce_migrate_skip.txt>` — the CE skip list (internal-
    history steps only; mod_migrate exits 2 before running anything if an entry
    names no discovered file).
    """
    if API_DIR not in sys.path:
        sys.path.insert(0, API_DIR)
    import database  # type: ignore
    from tools.mod_migrate import main as mod_migrate_main

    argv = list(argv) if argv else []
    # The skip list names REAL migration steps, so it is only meaningful with
    # the real migrations dir: inject it unless the caller already passed a
    # --skip-file, or overrode --migrations-dir (tests / dry-run harnesses
    # bring their own dir and pass their own --skip-file if they want one).
    if "--skip-file" not in argv and "--migrations-dir" not in argv:
        argv = ["--skip-file", SKIP_FILE] + argv

    fresh_db = False
    for phase, step in (("init", database.initialize), ("ddl", database.create_tables)):
        try:
            step()
        except Exception as exc:  # noqa: BLE001 — never leak the message (may carry a DSN)
            print(f"ce-migrate: FAILED at {phase}: {type(exc).__name__}", file=sys.stderr)
            return 1
        if phase == "init":
            # P18-F1b: capture the from-scratch gate BETWEEN init and ddl — create_tables
            # writes the mod_schema_version marker, so it must be read BEFORE ddl runs.
            fresh_db = _fresh_db_gate(database)

    # P18-F1b: a from-scratch DB (empty ledger AND no schema marker) gets the fresh-install
    # baseline manifest: steps create_tables() already builds are recorded, not executed.
    # Skipped if the caller already passed --baseline-list or overrode --migrations-dir.
    if fresh_db and "--baseline-list" not in argv and "--migrations-dir" not in argv:
        argv = argv + ["--baseline-list", FRESH_BASELINE]
        print("ce-migrate: fresh DB — applying tools/fresh_install_baseline.txt",
              file=sys.stderr)

    # CE-NOPAID-4.13d: the paid add-on migrations dir is forwarded ONLY on a paid
    # tree (utils/paid_import.is_paid_tree, the ONE edition predicate) and ONLY if
    # the dir exists — on CE nothing is added, and a missing extra dir is a no-op
    # (exit 0), never an error. Appended after the :114 skip-file and :132
    # baseline guards so those guards still see the caller's own argv flags.
    from utils.paid_import import is_paid_tree
    if (is_paid_tree() and os.path.isdir(PAID_MIGRATIONS_DIR)
            and "--extra-migrations-dir" not in argv):
        argv = argv + ["--extra-migrations-dir", PAID_MIGRATIONS_DIR]

    try:
        rc = mod_migrate_main(argv)
    except Exception as exc:  # noqa: BLE001 — same rule: type only, never the message
        print(f"ce-migrate: FAILED at migrate: {type(exc).__name__}", file=sys.stderr)
        return 1
    if rc != 0:
        print(f"ce-migrate: FAILED at migrate: rc={rc} — api will NOT start until "
              f"the step is fixed (see the FAIL line above it)", file=sys.stderr)
    return rc


if __name__ == "__main__":
    # CE-DRYRUN: main() takes the CLI argv verbatim; calling main() dropped
    # every flag the compose service / operator passed (--dry-run, --no-seeds),
    # so a dry-run silently committed. Forward sys.argv[1:].
    sys.exit(main(sys.argv[1:]))
