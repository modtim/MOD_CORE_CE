class _AutoRetryS3Proxy:
    """Proxy that catches SignatureDoesNotMatch and reinitializes MinIO credentials once."""

    def __init__(self, client_attr_name):
        # Store which class attribute to dereference (always reads fresh from MinioClient)
        self._attr_name = client_attr_name

    @property
    def _real(self):
        return getattr(MinioClient, self._attr_name)

    def __getattr__(self, name):
        attr = getattr(self._real, name)
        if not callable(attr):
            return attr

        def wrapper(*args, **kwargs):
            try:
                return attr(*args, **kwargs)
            except Exception as e:
                if "SignatureDoesNotMatch" in str(e) and not MinioClient._reinit_attempted:
                    MinioClient._reinit_attempted = True
                    logger.warning("SignatureDoesNotMatch — reinitializing MinIO client and retrying")
                    MinioClient.reinitialize()
                    # _real now points to the fresh client via property
                    fresh_attr = getattr(self._real, name)
                    result = fresh_attr(*args, **kwargs)
                    MinioClient._reinit_attempted = False
                    return result
                raise
        return wrapper


class S3Client:
    """
    A client for interacting with S3-compatible object storage (versitygw /

    This client is for API SERVICE use only - it uses service account credentials.
    For worker containers, use the per-task STS credentials issued by
    POST /workers/tasks/{task_id}/credentials (routers/worker_tasks.py).

    TENANT ISOLATION: Each tenant has their own bucket (tenant-{id}-files).
    Pass tenant_id to constructor or use set_tenant() to switch contexts.
    """

    _credentials_loaded = False
    _client = None
    _presigned_client = None
    _endpoint = None
    _external_endpoint = None
    _access_key = None
    _secret_key = None

    _reinit_attempted = False  # Prevent infinite reinit loops

    def __init__(self, tenant_id: int = None):
        """
        Initialize MinIO client for a specific tenant.

        Args:
            tenant_id: The tenant ID for bucket isolation. Required for operations.
        """
        self._ensure_credentials_loaded()

        self.tenant_id = tenant_id
        self.bucket_name = get_tenant_bucket_name(tenant_id) if tenant_id else None
        self.secure = False
        self._is_byo = False

        # Use class-level clients (shared across instances)
        self.client = _AutoRetryS3Proxy('_client')
        self.presigned_client = _AutoRetryS3Proxy('_presigned_client')
        self.endpoint = MinioClient._endpoint
        self.external_endpoint = MinioClient._external_endpoint
        self.access_key = MinioClient._access_key
        self.secret_key = MinioClient._secret_key

        # remove-minio-versitygw Gate 5 (5.6): if this tenant has an ACTIVE BYO-S3
        # StorageConnection, route ALL of their file ops (upload, presign, list,
        # delete) to their own endpoint/bucket instead of the house default. The
        # browser talks straight to the tenant endpoint, so the presigned client
        # is bound there too. resolve_backend never raises — a failed lookup just
        # leaves the house-default clients in place.
        if tenant_id:
            try:
                from utils import storage
                cfg = storage.resolve_backend(tenant_id)
                if getattr(cfg, "is_byo", False):
                    # BUG-860d: BYO-S3 per-tenant clients get the same bounded
                    # pool as the house default — a tenant's hung backend must
                    # not pin the /complete transaction either.
                    self.client = _bound_client(
                        storage.build_client_for_config(cfg, presigned=False))
                    self.presigned_client = _bound_client(
                        storage.build_client_for_config(cfg, presigned=True))
                    self.bucket_name = cfg.bucket
                    self.endpoint = cfg.internal_endpoint
                    self.external_endpoint = cfg.external_endpoint
                    self.access_key = cfg.access_key
                    self.secret_key = cfg.secret_key
                    self.secure = cfg.internal_secure
                    self._is_byo = True
                    logger.info(
                        "MinIO Client tenant %s → BYO-S3 endpoint %s bucket %s",
                        tenant_id, cfg.internal_endpoint, cfg.bucket)
            except Exception as exc:  # noqa: BLE001 — never block on BYO resolution
                logger.warning(
                    "MinIO Client tenant %s: BYO resolution failed (%s); house default.",
                    tenant_id, exc)

        if tenant_id:
            logger.info(f"MinIO Client initialized for tenant {tenant_id}, bucket: {self.bucket_name}")

    @classmethod
    def reinitialize(cls):
        """Force re-read credentials and recreate clients.
        Called automatically on SignatureDoesNotMatch errors.
        """
        from utils import storage
        storage.reset()
        cls._credentials_loaded = False
        cls._client = None
        cls._presigned_client = None
        cls._ensure_credentials_loaded()
        logger.info("MinIO client reinitialized (credentials reloaded)")

    @classmethod
    def _ensure_credentials_loaded(cls):
        """Load credentials once and cache at class level.

        Delegates all backend/endpoint/credential resolution to utils.storage —
        the single source of truth (Gate 0). MinioClient is now a thin wrapper
        that reuses storage's cached service + presigned clients, so a backend
        swap (minio → versitygw) or per-tenant BYO-S3 resolution is a config
        concern there, not here. Credential policy (Vault service account, no
        root fallback) is enforced in storage._load_service_credentials.
        """
        if cls._credentials_loaded:
            return

        from utils import storage
        cfg = storage.get_storage_config()
        cls._endpoint = cfg.internal_endpoint
        cls._external_endpoint = cfg.external_endpoint
        cls._access_key = cfg.access_key
        cls._secret_key = cfg.secret_key
        # BUG-860d: house-default clients get the bounded pool (see _bound_client).
        cls._client = _bound_client(storage.get_service_client())
        cls._presigned_client = _bound_client(storage.get_presigned_client())

        logger.info(
            "MinioClient initialised via utils.storage (backend=%s endpoint=%s external=%s)",
            cfg.backend, cls._endpoint, cls._external_endpoint)
        if is_debug_mode() and cls._access_key:
            logger.info("Using credentials - Access Key: %s... (first 10 chars)", cls._access_key[:10])
        else:
            logger.info("Using credentials (Access Key redacted - set DEBUG_MODE=true to view)")

        cls._credentials_loaded = True

    def set_tenant(self, tenant_id: int):
        """Switch to a different tenant's bucket."""
        self.tenant_id = tenant_id
        self.bucket_name = get_tenant_bucket_name(tenant_id)
        return self

    def get_s3_credentials_for_user(self, user_token: str, force_refresh: bool = False) -> dict:
        """
        Get tenant-scoped S3 credentials for a specific user.

        remove-minio-versitygw P7: canonical rename of the legacy
        ``get_minio_credentials_for_user`` (KeycloakSTSClient, AutomatedPipeline).
        The old name remains a REAL alias to this method (see below).

        Unlike the service-account clients on this instance, the returned
        credentials are a short-lived scoped STS session for the caller's
        tenant bucket (minted via utils.sts_session.assume_role against the
        active backend; there is no worker-side MinIO STS exchange anymore).

        Args:
            user_token: The user's Keycloak access token (identity context;
                the live mint is scoped by tenant, not by token exchange).
            force_refresh: Accepted for API compatibility; sessions are minted
                fresh on every call, so this is a no-op.

        Returns:
            Dict with: access_key, secret_key, session_token, expiry
            (expiry: tz-aware UTC datetime when the session expires).
        """
        if not user_token:
            raise ValueError("get_s3_credentials_for_user: user_token is required")
        if not self.tenant_id:
            raise ValueError("get_s3_credentials_for_user: tenant_id must be set before minting")

        from utils import storage, sts_session

        cfg = storage.resolve_backend(self.tenant_id)
        bucket = cfg.bucket or get_tenant_bucket_name(self.tenant_id)
        ttl_s = sts_session.DEFAULT_SESSION_TTL_S
        minted = sts_session.assume_role(
            cfg.internal_endpoint,
            access_key=cfg.access_key,
            secret_key=cfg.secret_key,
            bucket=bucket,
            session_name=f"mod-user-t{self.tenant_id}"[:64],
            ttl_seconds=ttl_s,
            session_policy=sts_session.build_session_policy(bucket),
            region=(getattr(cfg, "region", None) or "us-east-1"),
            secure=cfg.internal_secure,
        )
        logger.info(
            "Minted tenant-scoped S3 session for tenant %s (bucket=%s expires_at=%s)",
            self.tenant_id, bucket, minted["expires_at"])
        return {
            "access_key": minted["access_key"],
            "secret_key": minted["secret_key"],
            "session_token": minted["session_token"],
            "expiry": minted["expires_at"],
        }

    # remove-minio-versitygw P7 — the old public name stays as a REAL alias to
    # the SAME method (not a copy), so every existing caller keeps working.
    get_minio_credentials_for_user = get_s3_credentials_for_user

    def ensure_bucket_exists(self):
        """
        Ensure the tenant's bucket exists. Creates it if it doesn't.
        Called automatically on first operation, or explicitly during tenant creation.
        """
        if not self.bucket_name:
            raise ValueError("tenant_id must be set before bucket operations")

        if not self.client.bucket_exists(bucket_name=self.bucket_name):
            logger.info(f"Creating bucket '{self.bucket_name}' for tenant {self.tenant_id}")
            self.client.make_bucket(bucket_name=self.bucket_name)
            logger.info(f"Bucket '{self.bucket_name}' created successfully")
            # remove-minio-versitygw Gate 3 (D4): no bucket-notification wiring
            # here anymore — file_event triggers are emitted API-side on
            # confirm-upload / delete / worker-output confirmation.
        return True

    def create_folder(self, folder_path: str) -> str:
        """
        Creates a folder in MinIO by creating an empty object with a trailing slash.
        In S3/MinIO, folders are represented as empty objects with keys ending in '/'.

        Note: folder_path should NOT include tenant prefix - bucket provides isolation.
        """
        try:
            self.ensure_bucket_exists()

            # Ensure folder_path ends with '/'
            if not folder_path.endswith('/'):
                folder_path = folder_path + '/'

            # Create empty object to represent folder
            from io import BytesIO
            empty_stream = BytesIO(b'')
            self.client.put_object(
                bucket_name=self.bucket_name,
                object_name=folder_path,
                data=empty_stream,
                length=0,
                content_type='application/x-directory'
            )
            logger.info(f"Successfully created folder {folder_path} in {self.bucket_name}")
            return f"s3://{self.bucket_name}/{folder_path}"
        except S3Error as e:
            logger.error(f"MinIO S3Error during folder creation: {e}")
            raise
        except Exception as e:
            logger.error(f"An unexpected error occurred during MinIO folder creation: {e}")
            raise

    async def upload_file(self, object_name: str, file_stream: BinaryIO, file_size: int, content_type: str) -> str:
        """
        Uploads a file stream to MinIO.

        Note: object_name should NOT include tenant prefix - bucket provides isolation.
        """
        try:
            self.ensure_bucket_exists()

            # Upload the file stream
            self.client.put_object(
                bucket_name=self.bucket_name,
                object_name=object_name,
                data=file_stream,
                length=file_size,
                content_type=content_type
            )
            logger.info(f"Successfully uploaded {object_name} to {self.bucket_name}")
            return f"s3://{self.bucket_name}/{object_name}"
        except S3Error as e:
            logger.error(f"MinIO S3Error during upload: {e}")
            raise
        except Exception as e:
            logger.error(f"An unexpected error occurred during MinIO upload: {e}")
            raise

    def delete_folder(self, folder_path: str) -> bool:
        """
        Deletes a folder and all its contents from MinIO.
        In S3/MinIO, this means deleting all objects with the folder prefix.

        Note: folder_path should NOT include tenant prefix - bucket provides isolation.
        """
        try:
            if not self.bucket_name:
                raise ValueError("tenant_id must be set before bucket operations")

            # Ensure folder_path ends with '/'
            if not folder_path.endswith('/'):
                folder_path = folder_path + '/'

            # List all objects with this prefix
            objects = self.client.list_objects(
                bucket_name=self.bucket_name,
                prefix=folder_path,
                recursive=True
            )

            # Collect object names to delete
            objects_to_delete = [obj.object_name for obj in objects]

            if not objects_to_delete:
                logger.info(f"No objects found for folder {folder_path}")
                return True

            # Delete all objects
            for obj_name in objects_to_delete:
                self.client.remove_object(bucket_name=self.bucket_name, object_name=obj_name)

            # Also delete the folder marker itself
            try:
                self.client.remove_object(bucket_name=self.bucket_name, object_name=folder_path)
            except:
                pass  # Folder marker might not exist

            logger.info(f"Successfully deleted folder {folder_path} and {len(objects_to_delete)} objects from {self.bucket_name}")
            return True

        except S3Error as e:
            logger.error(f"MinIO S3Error during folder deletion: {e}")
            raise
        except Exception as e:
            logger.error(f"An unexpected error occurred during MinIO folder deletion: {e}")
            raise

    def delete_file(self, object_name: str) -> bool:
        """
        Deletes a specific file from MinIO.

        Note: object_name should NOT include tenant prefix - bucket provides isolation.
        """
        try:
            if not self.bucket_name:
                raise ValueError("tenant_id must be set before bucket operations")

            self.client.remove_object(bucket_name=self.bucket_name, object_name=object_name)
            logger.info(f"Successfully deleted {object_name} from {self.bucket_name}")
            return True
        except S3Error as e:
            logger.error(f"MinIO S3Error during file deletion: {e}")
            raise
        except Exception as e:
            logger.error(f"An unexpected error occurred during MinIO file deletion: {e}")
            raise
