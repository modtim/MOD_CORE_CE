# CORE/utils/s3_client.py
"""
S3 (object-storage) Client for API Service
============================

SECURITY NOTE (CMMC/ISO 27001/TPN Compliance):
This client is used by the API service (a trusted, controlled component).
It uses service account credentials generated by minio-setup, NOT root credentials.

TENANT ISOLATION (TPN CS-1 Content Security):
Each tenant gets their own bucket (tenant-{id}-files) for complete data isolation.
This ensures:
- Studio content from different clients is physically separated
- Breach of one tenant doesn't expose other tenants
- Easier compliance audits and data deletion (GDPR)

The API service is different from worker containers:
- API runs in a controlled container with mounted credentials
- Workers are potentially distributed and should NEVER have static credentials
- Workers receive short-lived STS credentials per task via the API

For worker storage access:
    The Go mod-worker calls POST /workers/tasks/{task_id}/credentials
    (see routers/worker_tasks.py) to obtain scoped STS credentials,
    then passes them to a minio-client sidecar for download/upload.
"""

