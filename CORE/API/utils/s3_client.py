# ---------------------------------------------------------------------------
# BUG-860d — bounded HTTP timeouts on EVERY MinioClient construction path.
#
# Since BUG-860c (26e5f62cb) services/task_output_scan.py fetches worker
# output BYTES inside the worker's /complete request while that request's
# DB session/transaction is open. minio's own default socket timeout is
# 5 MINUTES per connect/read with 5 retries, so a hung S3 / BYO-S3 backend
# can pin a DB connection for ~hours: the request never returns, the
# transaction stays open, and the pool leaks. We inject an explicit
# urllib3.PoolManager (minio accepts one via ``http_client=``) on every
# client this module builds — house default AND per-tenant BYO-S3 — with a
# bounded connect + read timeout and a bounded retry budget.
#
# Tunables live in the platform-settings registry (never env vars):
#   storage.s3_connect_timeout_s  default 5
#   storage.s3_read_timeout_s     default 60
# The read timeout is PER SOCKET READ, not a total transfer deadline, so
# 60s stays safe for large uploads/downloads (multi-GB objects stream in
# many short reads). Deliberately NO total deadline.
# ---------------------------------------------------------------------------
S3_CONNECT_TIMEOUT_KEY = "storage.s3_connect_timeout_s"
S3_READ_TIMEOUT_KEY = "storage.s3_read_timeout_s"
_S3_CONNECT_TIMEOUT_DEFAULT = 5
_S3_READ_TIMEOUT_DEFAULT = 60
_S3_RETRY_TOTAL = 2
_S3_BACKOFF_FACTOR = 0.2
_S3_STATUS_FORCELIST = [500, 502, 503, 504]

def _validate_timeout_bounds(lo: int, hi: int):
    """Build a platform-settings validator for a seconds-valued timeout."""
    def _check(value: int) -> None:
        if not isinstance(value, int) or value < lo or value > hi:
            raise ValueError(
                f"timeout must be between {lo} and {hi} seconds")
    return _check


_psr.register(
    S3_CONNECT_TIMEOUT_KEY,
    int,
    _S3_CONNECT_TIMEOUT_DEFAULT,
    restart_required=False,
    validator=_validate_timeout_bounds(1, 300),
    group="storage",
    description="Per-socket CONNECT timeout (seconds) for the API's S3/"
                "MinIO clients (house default + per-tenant BYO-S3). Bounds "
                "how long a dead/unreachable backend can hold a request open.",
)
_psr.register(
    S3_READ_TIMEOUT_KEY,
    int,
    _S3_READ_TIMEOUT_DEFAULT,
    restart_required=False,
    validator=_validate_timeout_bounds(1, 3600),
    group="storage",
    description="Per-socket READ timeout (seconds) for the API's S3/MinIO "
                "clients. Per read, not a total transfer deadline, so big "
                "uploads/downloads are unaffected.",
)


def _s3_timeout_seconds(db=None) -> tuple:
    """Resolve (connect, read) timeout seconds from the registry (DB > env > default).

    A DB failure (no session / broken pipe) degrades to the code defaults —
    storage must stay available, and a missing timeout is strictly worse than
    a wrong one, so we never raise out of here.
    """
    out = []
    for key, default in ((S3_CONNECT_TIMEOUT_KEY, _S3_CONNECT_TIMEOUT_DEFAULT),
                         (S3_READ_TIMEOUT_KEY, _S3_READ_TIMEOUT_DEFAULT)):
        try:
            value = _psr.get_setting(key, db=db)
        except Exception as exc:  # noqa: BLE001 — degrade to the safe default
            logger.warning("s3_client: %s unreadable (%s); using %ss.", key, exc, default)
            value = default
        try:
            out.append(max(1, int(value)))
        except (TypeError, ValueError):
            out.append(default)
    return tuple(out)


def _build_http_pool(db=None) -> PoolManager:
    """A urllib3.PoolManager mirroring minio's own defaults, with bounded timeouts.

    minio builds ``urllib3.PoolManager(timeout=Timeout(connect=300, read=300),
    maxsize=10, cert_reqs=..., ca_certs=..., retries=Retry(total=5, ...))``
    when no ``http_client=`` is passed. We reproduce every knob (TLS behaviour
    unchanged: same cert_reqs + ca_certs resolution) and only tighten the
    socket timeouts and the retry budget: 5 MINUTES x 5 retries on a hung
    backend is hours of a held-open DB transaction.
    """
    connect_s, read_s = _s3_timeout_seconds(db=db)
    return PoolManager(
        timeout=_U3Timeout(connect=connect_s, read=read_s),
        maxsize=10,
        cert_reqs='CERT_REQUIRED',
        ca_certs=os.environ.get('SSL_CERT_FILE') or certifi.where(),
        retries=_U3Retry(
            total=_S3_RETRY_TOTAL,
            backoff_factor=_S3_BACKOFF_FACTOR,
            status_forcelist=list(_S3_STATUS_FORCELIST),
        ),
    )


def _bound_client(client, db=None):
    """Give a storage-built Minio client bounded HTTP timeouts. Returns it.

    ``utils/storage.py`` is the single place object-storage clients are built
    (tests/test_no_root_cred_storage_clients.py enforces that), so this module
    must not call ``Minio(...)`` itself — instead it replaces the pool the
    client would otherwise have gotten from minio's 5-minute default with the
    bounded one above, which is exactly what passing ``http_client=`` to the
    constructor would have produced.
    """
    if client is None:
        return client
    if not hasattr(client, "_http"):
        # minio's internal pool attribute name changed (or this isn't a
        # minio.Minio instance) — skip the swap rather than silently setting
        # an attribute minio never reads, which would leave the client on
        # minio's 5-minute default with no signal that the timeout is unbound.
        logger.warning(
            "s3_client: client has no '_http' attribute (minio API may "
            "have changed); bounded timeouts NOT applied, client keeps "
            "whatever pool it was constructed with.")
        return client
    try:
        client._http = _build_http_pool(db=db)
    except Exception as exc:  # noqa: BLE001 — never fail storage on a timeout knob
        logger.warning("s3_client: bounded http pool unavailable (%s); "
                       "client keeps minio's default pool.", exc)
    return client

