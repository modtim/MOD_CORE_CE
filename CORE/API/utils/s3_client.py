def get_tenant_bucket_name(tenant_id: int, db: Optional[Session] = None) -> str:
    """
    Resolve the bucket name for a tenant.

    TPN CS-1 Compliance: Each tenant gets isolated storage.

    remove-minio-versitygw Gate 5 (5.6) / BYO-S3: routes through
    ``utils.storage.resolve_backend`` so a tenant with an ACTIVE BYO-S3
    ``StorageConnection`` gets THEIR bucket back, not the house one. Falls back
    to the house-default format (``tenant-{id}-files``) when there's no active
    BYO connection, no ``db`` session available, or resolution otherwise fails —
    this mirrors ``resolve_backend``'s never-raise contract so storage stays
    available rather than failing closed on a config lookup.

    ``utils.minio_helpers.get_tenant_bucket_name`` delegates to this
    implementation; there is only one place bucket names are actually computed.
    """
    house_default = f"tenant-{tenant_id}-files"
    if tenant_id is None:
        return house_default
    try:
        from utils import storage
        cfg = storage.resolve_backend(tenant_id, db)
        return cfg.bucket or house_default
    except Exception as exc:  # noqa: BLE001 — never fail closed on resolution
        logger.warning(
            "get_tenant_bucket_name(tenant=%s): BYO resolution failed (%s); house default.",
            tenant_id, exc)
        return house_default


