def reset_repair_budget(
    request: ResetRepairBudgetRequest,
    _auth: BuildAuthContext = Depends(require_build_task_token),
    db: Session = Depends(get_db),
):
    """Zero the repair counters + history on a BuildSpec.

    The test-and-repair stage calls this once at the start of a fresh
    loop run. Without it, a spec that exhausted its budget once stays
    exhausted forever — when the orchestrator re-dispatches the task
    (user clicks Retry, worker restarts mid-attempt), the next loop
    sees the API reject every repair with "budget exhausted" and
    bails in 2 attempts. Stage repro: spec 10, history shows 10 real
    attempts from a prior run; user retry produced an instant FAIL.

    Returns the prior counter values so the stage can log them.
    Not destructive — repair_history is preserved under
    repair_history_archived (capped to 30 entries) so post-mortem
    inspection can still see what happened on the prior run.
    """
    try:
        return _node_defs_task_queue_service.reset_repair_budget(db, request=request, auth=_auth)
    except _ServiceError as exc:
        _raise_http(exc)

