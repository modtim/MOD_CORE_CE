# NODE-BUILDER-DAY1 (REV follow-up 11-14) — shared guards for
# POST /v1/woodsman/upload-image. The REV that blocked fe6ca8f840 quoted
# "no tar size cap and no image_name/tag regex exist in the endpoint
# (pre-existing, both branches)", so these two guards sit ABOVE the branch
# split and apply to CE and paid alike; the tag-collision/namespace logic
# below is CE-only and the paid/registry branch lines stay byte-identical.
_UPLOAD_IMAGE_MAX_BYTES = 2 * 1024 * 1024 * 1024  # 2 GiB docker-load tarball
_UPLOAD_IMAGE_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,63}$")
_UPLOAD_IMAGE_TAG_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,30}$")
_CE_UPLOAD_NAMESPACE = "mod-node-upload"


def _tar_repo_tags(tar_path: str) -> list:
    """RepoTags declared in a docker-load tarball's manifest.json member.

    Reads that one member only (tarfile, nothing extracted to disk). Returns
    [] for anything that is not a readable tar - docker load fails on those
    anyway, so the guard must not turn a legit load into a 500.
    """
    import json
    import tarfile

    try:
        with tarfile.open(tar_path) as tf:
            for member in tf.getmembers():
                if member.isfile() and member.name.endswith("manifest.json"):
                    manifest = json.loads(tf.extractfile(member).read())
                    return [t for t in (manifest.get("RepoTags") or []) if isinstance(t, str) and t]
    except Exception:
        return []
    return []


_CE_UPLOAD_REF_RE = re.compile(r"^[a-z0-9][a-z0-9._/-]{0,127}$")


def _ce_upload_namespaced_ref(repo_tag: str, tenant_id, user_id) -> str:
    """Namespace one uploaded RepoTag under mod-node-upload/<owner>/.

    The REV that blocked fe6ca8f840 left the loaded tag as executable_path
    verbatim, so an upload could point at (or overwrite) any host tag. Every
    CE upload lives under mod-node-upload/<tenant-or-user-id>/<name>:<tag>
    instead; the derived name is regex-checked before anything runs.
    """
    owner = f"tenant-{tenant_id}" if tenant_id else f"user-{user_id}"
    base, sep, tag_part = repo_tag.rpartition(":")
    if sep and "/" not in base and _UPLOAD_IMAGE_TAG_RE.match(tag_part):
        name, tag = base, tag_part
    else:
        name, tag = repo_tag, "latest"
    if not _CE_UPLOAD_REF_RE.match(name):
        raise HTTPException(
            status_code=400,
            detail="uploaded image name must match ^[a-z0-9][a-z0-9._/-]{0,127}$",
        )
    return f"{_CE_UPLOAD_NAMESPACE}/{owner}/{name}:{tag}"


async def upload_container_image(
    image_name: str = Form(...),
    tag: str = Form(default="latest"),
    node_name: str = Form(default=""),
    input_type: str = Form(default="image"),
    output_type: str = Form(default="image"),
    process_type: str = Form(default="CPU"),
    description: str = Form(default=""),
    image_file: UploadFile = File(...),
    current_user: models.User = Depends(require_active_and_onboarded_user),
    db: Session = Depends(get_db),
):
    """
    Upload a pre-built Docker image tarball to the local container registry.

    The image is stored under the tenant's namespace in the local registry:
      registry:5000/tenant-{id}/{image_name}:{tag}

    Optionally creates a NodeDefinition so the container appears in the
    workflow builder's node library.
    """
    import os
    import subprocess
    import tempfile

    local_registry = tenant_registry()
    tenant_id = current_user.tenant_id
    # NODE-BUILDER-DAY1 (REV follow-up 11-14) — the two guards the REV quoted
    # as missing in BOTH branches (its NIT 1: "no tar size cap and no image_name
    # regex exist in the endpoint ... Pre-existing for paid too"). They sit
    # ABOVE the CE/paid split so both branches share them; nothing else here
    # touches the paid/registry path.
    if not _UPLOAD_IMAGE_NAME_RE.match(image_name or ""):
        raise HTTPException(
            status_code=400,
            detail="image_name must match ^[a-z0-9][a-z0-9._-]{0,63}$",
        )
    if not _UPLOAD_IMAGE_TAG_RE.match(tag or ""):
        raise HTTPException(
            status_code=400,
            detail="tag must match ^[A-Za-z0-9][A-Za-z0-9._-]{0,30}$",
        )
    # HARBOR-J2 — CE LAN installs ship no tenant registry (tenant_registry()
    # is ""), and this endpoint's whole contract is "push into the tenant's
    # namespace": with "" the ref composes to the malformed `/tenant-N/...`
    # and docker tag/push fail with a 500. Fail closed with a 400 BEFORE any
    # subprocess runs — no leading-slash ref, no tenant segment, no push, and
    # no image can be routed to another tenant's or the platform registry.
    # NODE-BUILDER-DAY1 — CE only: a default LAN install has no registry, but
    # the node builder must work on day 1. There the docker-load image stays
    # in the host image store under its loaded name (no tag/push). Paid keeps
    # the registry requirement unchanged.
    ce_local_store = not local_registry and is_ce_edition()
    if not local_registry and not ce_local_store:
        raise HTTPException(
            status_code=400,
            detail="No local registry configured; docker-load upload needs one",
        )
    full_image = (
        f"{local_registry}/tenant-{tenant_id}/{image_name}:{tag}"
        if local_registry else f"{image_name}:{tag}"
    )

    # Save uploaded tarball to temp file
    # NODE-BUILDER-DAY1 (REV follow-up 11-14) — the chunk loop used to be
    # uncapped (REV NIT 1). The ASGI UploadSizeCapMiddleware already answers
    # 413 for /v1/woodsman/* at the node_build settings cap (512 MB
    # default), but that cap is tenant/platform-tunable and the loop itself
    # had no bound, so the endpoint enforces its own 2 GiB hard ceiling here
    # too (no upload-specific limit constant existed for this endpoint).
    uploaded_bytes = 0
    over_cap = False
    with tempfile.NamedTemporaryFile(suffix=".tar", delete=False) as tmp:
        tmp_path = tmp.name
        while chunk := await image_file.read(1024 * 1024):  # 1MB chunks
            uploaded_bytes += len(chunk)
            if uploaded_bytes > _UPLOAD_IMAGE_MAX_BYTES:
                over_cap = True
                break
            tmp.write(chunk)

    try:
        if over_cap:
            raise HTTPException(
                status_code=413,
                detail=f"image tarball exceeds the {_UPLOAD_IMAGE_MAX_BYTES} byte limit",
            )
        # NODE-BUILDER-DAY1 (REV follow-up 11-14) — CE branch only: `docker
        # load -i <tar>` writes the tarball's OWN RepoTags straight into the
        # host image store, so an onboarded user uploading a tarball tagged
        # `postgres:16` / `mod-api:latest` overwrites a host tag before any
        # code runs (the REV that blocked fe6ca8f840, BLOCKING 1). Read the
        # tar's manifest.json RepoTags BEFORE the load and fail closed with
        # 409 naming the tag when it already exists in the host store
        # (`docker image inspect` rc=0) - no load, no overwrite.
        ce_repo_tags = _tar_repo_tags(tmp_path) if ce_local_store else []
        ce_existing_tags = []
        for _repo_tag in ce_repo_tags:
            probe = subprocess.run(
                ["docker", "image", "inspect", _repo_tag],
                capture_output=True, text=True, timeout=60,
            )
            if probe.returncode == 0:
                ce_existing_tags.append(_repo_tag)
        if ce_existing_tags:
            raise HTTPException(
                status_code=409,
                detail=f"Image tag {ce_existing_tags[0]} already exists on this host; upload refused",
            )

        # docker load
        result = subprocess.run(
            ["docker", "load", "-i", tmp_path],
            capture_output=True, text=True, timeout=300,
        )
        if result.returncode != 0:
            raise HTTPException(status_code=400, detail=f"docker load failed: {result.stderr[:500]}")

        # Parse the loaded image name from output
        # Format: "Loaded image: myimage:latest" or "Loaded image ID: sha256:abc..."
        loaded_image = None
        for line in result.stdout.splitlines():
            if "Loaded image:" in line and "Loaded image ID:" not in line:
                loaded_image = line.split("Loaded image:", 1)[1].strip()
                break

        if not loaded_image:
            loaded_image = f"{image_name}:{tag}"

        if ce_local_store:
            # NODE-BUILDER-DAY1 (REV follow-up 11-14) — never keep the tarball's
            # own tag in the host store: retag every loaded RepoTag into
            # mod-node-upload/<tenant-or-user-id>/<name>:<tag> and use that as
            # executable_path. The original tag is removed only because the
            # pre-load check above proved it did not exist before this load
            # (a pre-existing tag 409s and is never loaded, never rmi'd).
            loaded_tags = [
                line.split("Loaded image:", 1)[1].strip()
                for line in result.stdout.splitlines()
                if "Loaded image:" in line and "Loaded image ID:" not in line
            ] or [loaded_image]
            namespaced_refs = []
            for repo_tag in loaded_tags:
                namespaced_ref = _ce_upload_namespaced_ref(repo_tag, tenant_id, current_user.id)
                tag_result = subprocess.run(
                    ["docker", "tag", repo_tag, namespaced_ref],
                    capture_output=True, text=True, timeout=60,
                )
                if tag_result.returncode != 0:
                    raise HTTPException(status_code=500, detail=f"docker tag failed: {tag_result.stderr[:500]}")
                namespaced_refs.append(namespaced_ref)
                subprocess.run(["docker", "rmi", repo_tag], capture_output=True, timeout=30)
            full_image = namespaced_refs[0]
        else:
            # Tag for local registry
            tag_result = subprocess.run(
                ["docker", "tag", loaded_image, full_image],
                capture_output=True, text=True, timeout=60,
            )
            if tag_result.returncode != 0:
                raise HTTPException(status_code=500, detail=f"docker tag failed: {tag_result.stderr[:500]}")

            # Push to local registry
            push_result = subprocess.run(
                ["docker", "push", full_image],
                capture_output=True, text=True, timeout=600,
            )
            if push_result.returncode != 0:
                raise HTTPException(status_code=500, detail=f"docker push failed: {push_result.stderr[:500]}")

            # Clean up local images
            subprocess.run(["docker", "rmi", full_image], capture_output=True, timeout=30)
            if loaded_image != full_image:
                subprocess.run(["docker", "rmi", loaded_image], capture_output=True, timeout=30)

    finally:
        os.unlink(tmp_path)

    # Create a NodeDefinition if node_name was provided
    node_def_id = None
    if node_name:
        # Layer-1 admission on the pushed image ref. Closes the historical gap
        # where an uploaded tarball registered a node with no admission call at
        # all (D5). The ref is the tenant registry, so this passes for legit
        # uploads while still routing the path through the admission gate.
        _run_admission("image", {"executable_path": full_image}, current_user,
                       effective_tenant_id=tenant_id)
        existing = crud.get_node_definition_by_name(db, name=node_name, tenant_id=tenant_id)
        if existing:
            existing.executable_path = full_image
            db.commit()
            node_def_id = existing.id
        else:
            # LDF-3 §7 — user-driven image upload lands in the user's
            # private namespace; share-with-tenant is opt-in via the
            # promote endpoint after the fact.
            # B24-FIX3 — the ONE authority-scoped ce_included strip
            # (services/node_authoring_service.strip_user_ce_included). This
            # endpoint authenticates through `require_active_and_onboarded_user`
            # and has NO BuildAuthContext in scope, so auth=None -> the helper
            # always strips here (fail closed): a user-driven upload can never
            # stamp the system-only CE marker.
            new_def = crud.create_node_definition(
                db=db,
                user_id=current_user.id if not _is_service_account(current_user) else None,
                node_def=_node_authoring_service.strip_user_ce_included(
                    schemas.NodeDefinitionCreate(
                    name=node_name,
                    description=description or f"Custom container: {image_name}",
                    type="Custom",
                    executable_path=full_image,
                    process_type=process_type,
                    input_schema={"input_type": input_type, "file_mode": "both", "input_variables": "NONE"},
                    output_schema={"output_type": output_type, "file_mode": "both", "paired": True, "output_variables": "NONE"},
                    configuration_schema={"extra_variables": "NONE"},
                    batch_mode="batch",
                    cost_in_credits=0,
                    # Routing key for the downstream-dispatch path. See
                    # worker_tasks.py:189 — empty node_kind silently
                    # drops the dispatch.
                    node_kind=_derive_node_kind_from_image(full_image),
                ),
                    None, current_user,
                ),
                tenant_id=tenant_id,
            )
            node_def_id = new_def.id

    # Dispatch security scan in SaaS mode
    if _is_saas() and node_def_id:
        try:
            _dispatch_trivy_scan(db, node_def_id, full_image, tenant_id)
        except Exception as e:
            logger.warning("Failed to dispatch security scan for uploaded image (non-critical): %s", e)

    logging.info(
        "Uploaded container image %s for tenant %d (node_def=%s)",
        full_image, tenant_id, node_def_id,
    )

    return {
        "image": full_image,
        "registry": local_registry,
        "node_definition_id": node_def_id,
    }

@external_router.post("/nodes", status_code=status.HTTP_201_CREATED)
def author_external_node(
    req: schemas.ExternalNodeAuthoringRequest,
    response: Response,
    db: Session = Depends(get_db),
    user: models.User = Depends(require_node_authoring_key),
):
    """Register (source='image') or build-and-register (source='dockerfile') a
    self-built node, with no server-side LLM.

    - source='image' → register a pullable pre-built image as a user-private
      draft; responds 201 with the node id + scan status.
    - source='dockerfile' → build the self-contained Dockerfile via the
      existing local build pipeline, then register; responds 202 with a task
      id the caller can poll.

    Admission runs STRICTLY on this path (the WIZARD_ALLOW_ANY_IMAGE relaxation
    is not honored for externally-authored nodes). Scan / egress / non-root /
    sandbox gates apply exactly as for wizard-authored nodes.
    """
    tenant_id = user.tenant_id
    if req.source == "image":
        _run_admission(
            "image", {"executable_path": req.image}, user,
            effective_tenant_id=tenant_id, strict=True,
        )
        nd = schemas.NodeDefinitionCreate(
            name=req.name,
            type=req.type,
            executable_path=req.image,
            description=req.description,
            input_schema=req.input_schema,
            output_schema=req.output_schema,
            configuration_schema=req.configuration_schema,
            accepted_formats=req.accepted_formats,
            cost_in_credits=req.cost_in_credits,
            batch_mode=req.batch_mode,
            container_timeout=req.container_timeout,
            allowed_egress=req.allowed_egress,
            # FX.91 p2a — the manifest's declared hostnames ride along with
            # the dispatch-time allowlist (already validated + canonical by
            # the request schema; kept separate so the palette can show what
            # the author declared, p2b).
            egress_domains=req.egress_domains,
            use_sandbox_runtime=req.use_sandbox_runtime,
            gpu_variants=req.gpu_variants,
            process_type=req.process_type,
            node_kind=_derive_node_kind_from_image(req.image),
        )
        # B24-FIX3 — same ONE guard as the create branch in
        # services/node_authoring_service.py. `require_node_authoring_key`
        # returns only a models.User (no BuildAuthContext), and it explicitly
        # REJECTS service-principal keys (_reject_service_principal_key), so
        # auth=None here always strips — an externally-authored node can never
        # carry the system-only ce_included marker.
        nd = _node_authoring_service.strip_user_ce_included(nd, None, user)
        # user_id set -> a user-private draft (never trust role/tenant from the
        # body). node_role defaults to 'user' (tenant present); system_only
        # stays False; not published to the marketplace.
        new_def = crud.create_node_definition(
            db=db, node_def=nd, tenant_id=tenant_id, user_id=user.id,
        )
        if _is_saas() and new_def.executable_path and tenant_id:
            try:
                _dispatch_trivy_scan(db, new_def.id, new_def.executable_path, tenant_id)
            except Exception as e:
                logger.warning("External authoring: scan dispatch failed (non-critical): %s", e)
        response.status_code = status.HTTP_201_CREATED
        return schemas.ExternalNodeCreated(
            id=new_def.id, name=new_def.name,
            node_role=new_def.node_role, scan_status=new_def.scan_status,
        )

    # source == 'dockerfile' — build-from-context via the existing pipeline.
    # Enforce STRICT admission here first; the reused build path re-runs
    # admission non-strict, so this strict check is the binding gate that keeps
    # the any-image relaxation from admitting a non-allowlisted FROM.
    _run_admission(
        "dockerfile", {"dockerfile": req.dockerfile}, user,
        effective_tenant_id=tenant_id, strict=True,
    )
    blr = BuildLocalRequest(
        image_name=_node_image_slug(req.name),
        node_name=req.name,
        dockerfile=req.dockerfile,
        # Facade-supplied: the caller's Dockerfile is self-contained (defines
        # its own ENTRYPOINT reading /data/input -> /data/output). The
        # imagebuilder builds + pushes from the Dockerfile alone, so these are
        # intentionally empty.
        entrypoint_sh="",
        build_and_push_sh="",
        process_type=(req.process_type or "CPU"),
        cost_in_credits=req.cost_in_credits,
        description=req.description,
        container_env=req.container_env,
        gpu_variants=req.gpu_variants,
        node_metadata={
            "type": req.type,
            "input_schema": req.input_schema,
            "output_schema": req.output_schema,
            "configuration_schema": req.configuration_schema,
            "accepted_formats": req.accepted_formats,
            "batch_mode": req.batch_mode,
            "container_timeout": req.container_timeout,
            "allowed_egress": req.allowed_egress,
            "use_sandbox_runtime": req.use_sandbox_runtime,
        },
    )
    result = build_and_register_local(request=blr, current_user=user, db=db)
    response.status_code = status.HTTP_202_ACCEPTED
    return schemas.ExternalNodeBuildAccepted(
        task_id=int(result["task_id"]),
        step="external-node-authoring",
        status=result.get("status", "pending"),
    )

@external_router.post("/nodes/validate")
def validate_external_node(
    req: schemas.ExternalNodeAuthoringRequest,
    db: Session = Depends(get_db),
    user: models.User = Depends(require_node_authoring_key),
):
    """Admission dry-run for the MCP `validate_submission` tool.

    Runs the same STRICT admission as POST /nodes but returns a structured
    pass/fail + reason instead of raising 422, and creates/registers nothing.
    """
    if req.source == "image":
        result = _admission_dry_run(
            "image", {"executable_path": req.image}, user,
            effective_tenant_id=user.tenant_id, strict=True,
        )
    else:
        result = _admission_dry_run(
            "dockerfile", {"dockerfile": req.dockerfile}, user,
            effective_tenant_id=user.tenant_id, strict=True,
        )
    return {"passed": result.passed, "rule": result.rule, "reason": result.reason}

def adapt_container_to_node(
    request: ContainerAdaptRequest,
    current_user: models.User = Depends(require_active_and_onboarded_user),
    db: Session = Depends(get_db),
):
    """
    All-in-one: Analyze → Generate Dockerfile → Generate DAG → Build → Push → Register.

    Runs step 1 (ContainerAdapter) as a worker task. Steps 2-3 must be triggered
    separately after reviewing the generated files, or run manually.

    For teams that already have a working Docker image, use /generate-dag and
    /build-and-register directly — skip this endpoint entirely.
    """
    import os
    if not request.source_image:
        raise HTTPException(status_code=400, detail="source_image is required")

    # Script/Dockerfile-embed mode: when additional_instructions carries the
    # Dockerfile or script body, run admission on it now. The LLM output is
    # re-validated downstream at /build-and-register-local.
    if request.additional_instructions:
        body = request.additional_instructions
        lowered = body.lower()
        if "from " in lowered and "\n" in body:
            _run_admission("dockerfile", {"dockerfile": body}, current_user)
        else:
            # Treat free-form additional_instructions as a script body; the
            # interpreter comes from process_type hint (fallback python3).
            interp = "python3" if "python" in (request.process_type or "").lower() else "python3"
            _run_admission(
                "script",
                {"interpreter": interp, "script": body},
                current_user,
            )

    _adapter_slot_guard(db, current_user.tenant_id)

    env = {
        "SOURCE_IMAGE": request.source_image,
        "NODE_NAME": request.node_name,
        "INPUT_TYPE": request.input_type,
        "OUTPUT_TYPE": request.output_type,
        "PROCESS_TYPE": request.process_type,
        "COST_IN_CREDITS": str(request.cost_in_credits),
        "TENANT_ID": str(current_user.tenant_id) if current_user.tenant_id else "",
        **_build_llm_env("adapter"),
    }
    if request.additional_instructions:
        env["ADDITIONAL_INSTRUCTIONS"] = request.additional_instructions

    task_id = _enqueue_container_task(
        db, current_user.tenant_id, "containeradapter:latest", env,
        "container_adapter",
    )
    return {
        "task_id": task_id,
        "status": "pending",
        "message": f"Container adaptation started for '{request.node_name}'",
        "next_steps": [
            "Poll task status to see generated files",
            "Review and edit Dockerfile/DAG if needed",
            "Use /build-and-register to build the image and register the node",
        ],
    }

